/* Structure to hold information about the file being compressed */
typedef struct CompressInfo{
    FILE * file;                        // Pointer to the file that is being compressed
    char * file_path;                   // Stores the file path 
    int is_open_file;                   // Informs if the file is currently open and needs to be closed
    int total_symbols;                  // Number of total symbols in the file
    int n_symbols;                      // Number of unique symbols in the file
    char * symbols;                     // Array of symbols in the file
    float * probabilities;              // Array of probabilities of each symbol that resides in the file
    unsigned long long * new_symbols;   // Array of new bit sequences that represent the symbols in the file
    int * code_len;                     // Array of the code length for each new symbol generated by the algorithm
    int number_zeros;                   // Tells the number of '\0' characters in the file for safe decompression
}CompressInfo;


/*This struct is used to print the new symbols to the according file , utilizing a buffer with 1 byte*/
typedef struct BitWriter{
    FILE * file;            // Keeps the file we are writing on
    unsigned char buffer;   // Buffer that keeps the 8 bits that are going to be written on the file
    int flush_bits;         // Counter that keeps track how many bits are in the buffer , so it can flushout at 1 byte(8 bits)
}BitWriter;


/*Generic Binary Tree*/
typedef struct Node {
    int indx;             // The Index of the Symbol being written in the array of New Symbols
    int frequency;        // The sum of both childs frequency
    struct Node *left;    // Pointer to the left child
    struct Node *right;   // Pointer to the right child
} Node;